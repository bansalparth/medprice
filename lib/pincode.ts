export function pincodeToStateCode(pincode: string): string {
  const p3 = pincode.slice(0, 3);
  if (PREFIX_TO_STATE_CODE[p3]) return PREFIX_TO_STATE_CODE[p3];
  return FIRST_DIGIT_FALLBACK[pincode[0]] ?? "MH";
}

export function pincodeToCity(pincode: string): string {
  const p3 = pincode.slice(0, 3);
  if (PREFIX_TO_CITY[p3]) return PREFIX_TO_CITY[p3];
  const stateCode = pincodeToStateCode(pincode);
  return STATE_CODE_TO_CAPITAL[stateCode] ?? "Mumbai";
}
